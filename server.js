// ── Voice Transcription (OpenAI Whisper) ──
app.post('/api/voice-transcribe', async (req, res) => {
  const clientIp = req.ip || req.socket?.remoteAddress || 'unknown';
  if (!checkRateLimit(`voice:${clientIp}`, 60000, 10)) {
    return res.status(429).json({ error: 'Too many voice requests. Please wait.' });
  }

  try {
    const { audio, mimeType = 'audio/webm' } = req.body;
    if (!audio) return res.status(400).json({ error: 'No audio data provided' });

    const buffer = Buffer.from(audio, 'base64');
    if (buffer.length > 25 * 1024 * 1024) {
      return res.status(413).json({ error: 'Audio file too large. Maximum size is 25MB.' });
    }
    const ext = mimeType.includes('mp4') ? 'mp4' : mimeType.includes('ogg') ? 'ogg' : 'webm';
    const file = await toFile(buffer, `recording.${ext}`, { type: mimeType });

    const transcription = await openai.audio.transcriptions.create({
      file,
      model: 'whisper-1',
    });

    res.json({ text: transcription.text });
  } catch (e) {
    console.error('Voice transcription error:', e.message);
    res.status(500).json({ error: 'Transcription failed. Please type instead.' });
  }
});

app.post('/api/tts', async (req, res) => {
  const clientIp = req.ip || req.socket?.remoteAddress || 'unknown';
  if (!checkRateLimit(`tts:${clientIp}`, 60000, 20)) {
    return res.status(429).json({ error: 'Too many TTS requests. Please wait.' });
  }

  try {
    const { text } = req.body;
    if (!text) return res.status(400).json({ error: 'No text provided' });
    if (text.length > 1000) return res.status(400).json({ error: 'Text too long for TTS.' });

    const mp3 = await openai.audio.speech.create({
      model: 'tts-1',
      voice: 'nova',   // female, warm, friendly
      input: text,
      speed: 1.0,
    });

    const buffer = Buffer.from(await mp3.arrayBuffer());
    res.set('Content-Type', 'audio/mpeg');
    res.send(buffer);
  } catch (e) {
    console.error('TTS error:', e.message);
    res.status(500).json({ error: 'TTS failed' });
  }
});

