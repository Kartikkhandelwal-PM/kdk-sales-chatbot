// ── In-memory rate limiter ──
const _rlMap = new Map();
function checkRateLimit(key, windowMs, max) {
  const now = Date.now();
  const e   = _rlMap.get(key) || { n: 0, reset: now + windowMs };
  if (now > e.reset) { e.n = 0; e.reset = now + windowMs; }
  e.n++;
  _rlMap.set(key, e);
  return e.n <= max;
}
setInterval(() => { const now = Date.now(); for (const [k, e] of _rlMap) if (now > e.reset) _rlMap.delete(k); }, 300000);

