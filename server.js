function cosineSim(a, b) {
  let dot = 0, normA = 0, normB = 0;
  for (let i = 0; i < a.length; i++) {
    dot   += a[i] * b[i];
    normA += a[i] * a[i];
    normB += b[i] * b[i];
  }
  return dot / (Math.sqrt(normA) * Math.sqrt(normB));
}

function titleBoost(rawQuery, title) {
  // Split query into individual words, find specific identifiers (GSTR6, 26Q, ITR7, 24Q etc.)
  const words = rawQuery.toLowerCase().split(/[^a-z0-9]+/);
  const titleNorm = title.toLowerCase().replace(/[-\s]+/g, '');
  for (const word of words) {
    // Identifier = word with both letters AND digits (e.g. gstr6, 26q, itr7, 24q, 27eq)
    if (word.length >= 2 && /[a-z]/.test(word) && /\d/.test(word)) {
      if (titleNorm.includes(word)) return 0.18;
    }
  }
  return 0;
}

// Detect which product the user is focused on from the conversation history.
// Returns 'GST', 'TDS', 'ITR', or null (unknown/mixed).
// Only scans USER messages — bot's Q2 always mentions all three, which creates false ties.
function detectProductContext(messages) {
  const userText = messages.filter(m => m.role === 'user').map(m => m.content || '').join(' ');
  // Explicit multi-product signals → null (covers "all", "all three", "a mix", "all my clients")
  if (/\ball\b|\ba mix\b|\ball three\b/i.test(userText)) return null;
  const gst = (userText.match(/\bgst\b/gi) || []).length;
  const tds = (userText.match(/\btds\b/gi) || []).length;
  const itr = (userText.match(/\bitr\b/gi) || []).length;
  const max = Math.max(gst, tds, itr);
  if (max === 0) return null;
  // Only declare a winner if it has a clear majority — tie means mixed context
  if (gst === max && gst > tds && gst > itr) return 'GST';
  if (tds === max && tds > gst && tds > itr) return 'TDS';
  if (itr === max && itr > gst && itr > tds) return 'ITR';
  return null;
}

function retrieveByEmbedding(queryEmbedding, rawQuery = '', maxChars = 4000, productFilter = null) {
  // When product context is known, score articles from that product higher (+0.12 boost).
  // This prevents, e.g., an ITR ClearTax migration article from outranking the GST one.
  const scored = embeddedArticles.map(art => ({
    art,
    score: cosineSim(queryEmbedding, art.embedding)
      + titleBoost(rawQuery, art.title)
      + (productFilter && art.product === productFilter ? 0.12 : 0),
  }));
  scored.sort((a, b) => b.score - a.score);

  let result = '';

  if (!productFilter) {
    // No product specified — pick the best matching article from each product so the AI
    // can answer for GST, TDS, and ITR rather than defaulting to whichever scores highest globally.
    const seen = {};
    for (const { art, score } of scored) {
      if (score < 0.32) break;
      if (seen[art.product]) continue;
      if (result.length + art.content.length + 6 > maxChars) continue;
      result += art.content + '\n\n---\n\n';
      seen[art.product] = true;
      if (Object.keys(seen).length === 3) break;
    }
    return result;
  }

  for (const { art, score } of scored) {
    if (score < 0.32) break;
    if (result.length + art.content.length + 6 > maxChars) break;
    result += art.content + '\n\n---\n\n';
  }
  return result;
}

function retrieveByKeyword(query, maxChars = 4000, productFilter = null) {
  if (!query || allArticles.length === 0) return '';
  const keywords = query.toLowerCase()
    .replace(/[^a-z0-9\s]/g, ' ')
    .split(/\s+/)
    .filter(w => w.length > 2 && !STOPWORDS.has(w));
  if (keywords.length === 0) return '';

  // Also match stemmed singular/plural — e.g. "clients" matches "client" and vice versa
  const expandedKeywords = [...new Set(keywords.flatMap(kw => {
    if (kw.endsWith('s') && kw.length > 4) return [kw, kw.slice(0, -1)]; // clients → client
    return [kw, kw + 's'];                                                 // client → clients
  }))];

  const scored = allArticles.map(art => {
    const titleLower   = art.title.toLowerCase();
    const tagsLower    = art.tags.toLowerCase();
    const contentLower = art.content.toLowerCase();
    const score = expandedKeywords.reduce((sum, kw) => sum
      + (titleLower.includes(kw)   ? 5 : 0)
      + (tagsLower.includes(kw)    ? 3 : 0)
      + (contentLower.includes(kw) ? 1 : 0), 0)
      + (productFilter && art.product === productFilter ? 4 : 0); // boost matching product
    return { art, score };
  });
  scored.sort((a, b) => b.score - a.score);

  let result = '';

  if (!productFilter) {
    // No product specified — pick the best article from each product.
    const seen = {};
    for (const { art, score } of scored) {
      if (score < 3) break;
      if (seen[art.product]) continue;
      if (result.length + art.content.length + 6 > maxChars) continue;
      result += art.content + '\n\n---\n\n';
      seen[art.product] = true;
      if (Object.keys(seen).length === 3) break;
    }
    return result;
  }

  for (const { art, score } of scored) {
    if (score < 3) break;
    if (result.length + art.content.length + 6 > maxChars) break;
    result += art.content + '\n\n---\n\n';
  }
  return result;
}

// ── Hybrid retrieval: combines embedding cosine similarity + keyword scoring ──
// Always runs both methods and merges scores so neither alone can return a wrong article.
// Keyword component is weighted higher (0.6) because exact term matches (gstr1, books, etc.)
// are more reliable than semantic similarity for domain-specific documentation queries.
function retrieveHybrid(queryEmbedding, rawQuery, maxChars = 4000, productFilter = null) {
  if (allArticles.length === 0) return '';

  // Keyword scoring (reuse same logic as retrieveByKeyword)
  const keywords = rawQuery.toLowerCase()
    .replace(/[^a-z0-9\s]/g, ' ')
    .split(/\s+/)
    .filter(w => w.length > 2 && !STOPWORDS.has(w));
  const expandedKeywords = keywords.length === 0 ? [] : [...new Set(keywords.flatMap(kw =>
    (kw.endsWith('s') && kw.length > 4) ? [kw, kw.slice(0, -1)] : [kw, kw + 's']
  ))];
  const maxKwScore = expandedKeywords.length * 9; // max possible keyword score per article (title+tags+content)

  const scored = allArticles.map(art => {
    // Keyword score
    let kwScore = 0;
    if (expandedKeywords.length > 0) {
      const titleLower   = art.title.toLowerCase();
      const tagsLower    = art.tags.toLowerCase();
      const contentLower = art.content.toLowerCase();
      kwScore = expandedKeywords.reduce((sum, kw) => sum
        + (titleLower.includes(kw)   ? 5 : 0)
        + (tagsLower.includes(kw)    ? 3 : 0)
        + (contentLower.includes(kw) ? 1 : 0), 0)
        + (productFilter && art.product === productFilter ? 4 : 0);
    }

    // Embedding score (0 if no embedding available for this article)
    let embScore = 0;
    if (queryEmbedding && art.embedding) {
      embScore = cosineSim(queryEmbedding, art.embedding)
        + titleBoost(rawQuery, art.title)
        + (productFilter && art.product === productFilter ? 0.12 : 0);
    }

    // Hybrid: keyword-dominant (0.6) + embedding (0.4)
    const normKw = maxKwScore > 0 ? kwScore / maxKwScore : 0;
    const hybrid = embScore * 0.4 + normKw * 0.6;
    return { art, hybrid };
  });

  scored.sort((a, b) => b.hybrid - a.hybrid);

  const THRESHOLD = 0.20; // combined score floor — keyword alone at 1/3 max passes, embedding alone needs ~0.50
  let result = '';

  if (!productFilter) {
    const seen = {};
    for (const { art, hybrid } of scored) {
      if (hybrid < THRESHOLD) break;
      if (seen[art.product]) continue;
      if (result.length + art.content.length + 6 > maxChars) continue;
      result += art.content + '\n\n---\n\n';
      seen[art.product] = true;
      if (Object.keys(seen).length === 3) break;
    }
    return result;
  }

  for (const { art, hybrid } of scored) {
    if (hybrid < THRESHOLD) break;
    if (result.length + art.content.length + 6 > maxChars) break;
    result += art.content + '\n\n---\n\n';
  }
  return result;
}

